# ---------------------------------------------------------------------------
# A note on this eval's own limits, read before trusting its numbers
# ---------------------------------------------------------------------------
#
# --judge scores every response with the *same* model that answered the
# question (--model, unless --judge-model is given). A same-model judge has a
# known self-preference bias: it tends to rate its own family's answers more
# favorably than an independent judge would. Pass --judge-model with a
# different model (ideally a different vendor) to reduce this; the summary
# prints a warning when judge and answer models match, rather than silently
# presenting a same-model score as if it were independent.

