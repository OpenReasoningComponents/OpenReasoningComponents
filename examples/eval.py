def load_iris_components(path: str = "examples/components.json") -> list[dict]:
    with open(path) as f:
        return json.load(f)


def build_iris_component_context(components: list[dict]) -> str:
    statements = [c["statement"] for c in components]
    return "The following facts are known about the iris dataset:\n\n" + "\n".join(
        f"- {s}" for s in statements
    )


def build_iris_profile_context(*, sample_size: int = 8, seed: int = 0) -> str:
    """A realistic baseline: schema, summary statistics, and a small sample.

    This is what an agent (or analyst) would actually look at for a dataset
    this size -- not the full 150 rows. See the module docstring for why this,
    not a raw dump, is the fair "the agent looked at the data" comparison.
    """
    from sklearn.datasets import load_iris

    iris = load_iris()
    lines = [
        f"Dataset: iris, {len(iris.data)} rows, 4 numeric features + species.",
        "",
        "Schema:",
    ]
    for i, name in enumerate(iris.feature_names):
        vals = [row[i] for row in iris.data]
        lines.append(
            f"  - {name}: numeric, min={min(vals):.2f} max={max(vals):.2f} "
            f"mean={mean(vals):.2f} stdev={pstdev(vals):.2f}"
        )
    lines.append(
        "  - species: categorical, values: "
        + ", ".join(iris.target_names)
        + " (50 rows each)"
    )

    rng = random.Random(seed)
    idx = rng.sample(range(len(iris.data)), min(sample_size, len(iris.data)))
    lines.append("")
    lines.append(f"Sample of {len(idx)} rows:")
    lines.append(",".join([*iris.feature_names, "species"]))
    for i in idx:
        vals = ",".join(f"{v:.1f}" for v in iris.data[i])
        lines.append(f"{vals},{iris.target_names[iris.target[i]]}")

    return (
        "Here is a profile of the iris dataset (schema, summary statistics, "
        "and a small random sample -- not the full data):\n\n" + "\n".join(lines)
    )


def build_iris_raw_data_context() -> str:
    """The naive full-dump baseline (--include-raw-dump). Not the default."""
    from sklearn.datasets import load_iris

    iris = load_iris()
    lines = [",".join(iris.feature_names + ["species"])]
    for i in range(len(iris.data)):
        vals = ",".join(f"{v:.1f}" for v in iris.data[i])
        lines.append(f"{vals},{iris.target_names[iris.target[i]]}")

    return (
        "Here is the complete iris dataset:\n\n"
        "```csv\n" + "\n".join(lines) + "\n```\n\n"
        "The dataset has 150 rows with 4 numeric features and "
        "a categorical target (species: setosa, versicolor, virginica)."
    )


