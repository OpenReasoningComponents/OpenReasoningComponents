"""
Evaluate whether ORC components improve AI reasoning about a dataset.

Runs the same questions under three conditions:
  1. no_context   — question only
  2. profile      — question + schema, summary statistics, and a small random
                     sample of rows in the prompt
  3. components   — question + ORC component statements in the prompt

Measures both token count and response quality. The core hypothesis:
components achieve comparable accuracy to a realistic profile-based context
at a fraction of the token cost — and the gap widens as datasets grow.

`profile`, not a full CSV dump, is the baseline here because nobody actually
does the latter: no real system hands an LLM the entire raw table on every
question, and a large-context provider isn't a fair "raw data" competitor
either -- that's still a strawman, just with a bigger box. What an agent (or a
human analyst) realistically has is a schema, summary statistics and a
sample -- e.g. the output of `df.describe()` plus `df.sample()`, or what a
lightweight profiling/BI-copilot step would produce. That is what `profile`
builds, from plain csv/statistics -- no pandas dependency. The unrealistic
full-dump condition is still here (pass --include-raw-dump), because it's
useful as an explicit upper bound on how much a naive approach would cost, but
it is opt-in, not the headline comparison.

Two datasets, both fully self-contained -- no external system, checkout, or
network access beyond the Anthropic API is required for either:
  --dataset iris   The original toy demo (sklearn's Iris, 150 rows, one size).
                   This is what the very first version of this eval ran, kept
                   for comparison.
  --dataset churn  (default) A synthetic customer-churn dataset, at several
                   sizes (--sizes), generated by this script
                   (generate_customers below) and turned into components by
                   this script (build_churn_component_context below) --
                   this is the eval that can test whether the token gap
                   widens with dataset size, since the churn dataset can be
                   generated at any row count.

Requires: pip install anthropic scikit-learn scipy

Usage:
    python examples/eval.py --dry-run                      # no API calls; verify prompts/contexts
    python examples/eval.py --dataset churn --judge         # real run, auto-scored
    python examples/eval.py --dataset iris                  # the original demo
    python examples/eval.py --sizes 500 5000 --trials 3      # test whether the gap widens
    python examples/eval.py --include-raw-dump --dry-run    # add the naive full-CSV upper bound
"""

