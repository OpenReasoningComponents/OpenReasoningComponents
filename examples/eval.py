def generate_customers(n: int, *, seed: int = 0) -> list[dict[str, str]]:
    """A synthetic customer-churn dataset, pure stdlib, seeded for reproducibility.

    Churn probability: higher with a high discount (a real, if odd,
    relationship -- steep discounts often mark a customer already flagged as
    a retention risk), lower with tenure, higher for month-to-month
    contracts. Deliberately not linear or independent, so there's more than
    one true fact for the components condition to state.
    """
    rng = random.Random(seed)
    rows = []
    for i in range(n):
        tenure = rng.randint(0, 72)
        contract = rng.choices(
            ["month_to_month", "one_year", "two_year"], weights=[3, 1, 1]
        )[0]
        discount = round(rng.uniform(0.0, 0.35), 3)
        monthly_charges = round(rng.uniform(20.0, 120.0), 2)

        risk = 0.10
        if discount > 0.20:
            risk += 0.25
        risk -= min(tenure, 48) / 48 * 0.15
        if contract == "month_to_month":
            risk += 0.10
        elif contract == "two_year":
            risk -= 0.05
        risk = min(max(risk, 0.01), 0.95)
        churn = rng.random() < risk

        rows.append(
            {
                "customer_id": f"c{i + 1}",
                "tenure_months": str(tenure),
                "contract_type": contract,
                "discount": f"{discount:.3f}",
                "monthly_charges": f"{monthly_charges:.2f}",
                "churn": "true" if churn else "false",
            }
        )
    return rows


def generate_customers_csv(out_path: Path, *, rows: int, seed: int = 0) -> None:
    """Write a customers CSV at `rows` size using generate_customers above."""
    rows_data = generate_customers(rows, seed=seed)
    with out_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows_data[0].keys()))
        writer.writeheader()
        writer.writerows(rows_data)


def _churn_rate(rows: list[dict], predicate) -> float:
    matched = [r for r in rows if predicate(r)]
    return sum(1 for r in matched if r["churn"] == "true") / len(matched)


def _churn_odds_ratio(rows: list[dict], predicate) -> tuple[float, int, int]:
    """Odds ratio of churn for rows matching `predicate` vs. rows that don't."""
    a = b = c = d = 0
    for row in rows:
        churned = row["churn"] == "true"
        if predicate(row):
            a += churned
            b += not churned
        else:
            c += churned
            d += not churned
    odds_ratio = (a / b) / (c / d) if b and c and d else float("nan")
    return odds_ratio, a + b, c + d


def build_churn_component_context(customers_csv: Path) -> str:
    """Four ORC-shaped statements about the customers dataset: a column
    definition, a distribution, a threshold rule, and a segment -- each with
    real evidence computed from the data (odds ratios, sample sizes, segment
    size), not hand-typed numbers. This is exactly the kind of thing a
    components-producing system (per spec/component.md) would compute; this
    script computes it directly, the same way build_iris_component_context
    above does for Iris, rather than depending on any particular
    implementation of the spec.
    """
    with customers_csv.open(newline="") as f:
        rows = list(csv.DictReader(f))
    n = len(rows)
    discounts = [float(r["discount"]) for r in rows]

    threshold = 0.20
    _, n_high, n_low = _churn_odds_ratio(rows, lambda r: float(r["discount"]) > threshold)
    churn_high = _churn_rate(rows, lambda r: float(r["discount"]) > threshold)
    churn_low = _churn_rate(rows, lambda r: float(r["discount"]) <= threshold)

    def _is_loyal_two_year(row: dict) -> bool:
        return int(row["tenure_months"]) > 36 and row["contract_type"] == "two_year"

    segment_rows = [r for r in rows if _is_loyal_two_year(r)]
    segment_churn = (
        sum(1 for r in segment_rows if r["churn"] == "true") / len(segment_rows)
        if segment_rows
        else float("nan")
    )
    overall_churn = sum(1 for r in rows if r["churn"] == "true") / n

    statements = [
        "discount is a float column in the customers table representing the "
        f"discount rate applied to a customer's contract, ranging from "
        f"{min(discounts):.0%} to {max(discounts):.0%}.",
        f"Customer discounts range from {min(discounts):.0%} to "
        f"{max(discounts):.0%}, with a median of {median(discounts):.0%}.",
        f"Customers receiving discounts above {threshold:.0%} churn "
        f"substantially more often ({churn_high:.0%} vs. {churn_low:.0%}, "
        f"n={n_high + n_low}).",
        "A segment of long-tenure (>36 month) two-year-contract customers "
        f"(n={len(segment_rows)}) shows low churn ({segment_churn:.0%} vs. "
        f"{overall_churn:.0%} overall).",
    ]
    return "The following facts are known about the customers dataset:\n\n" + "\n".join(
        f"- {s}" for s in statements
    )


def build_churn_profile_context(
    customers_csv: Path, *, n_rows: int, sample_size: int = 8, seed: int = 0
) -> str:
    """A realistic baseline: schema, per-column summary stats, and a sample.

    This is what an agent would actually send as context for a dataset this
    size -- not the full file. It's built with plain csv/statistics, the same
    way a lightweight profiling step (or `df.describe()` + `df.sample()`)
    would, so it's a fair stand-in for "the agent looked at the data itself,"
    rather than the weaker "the agent saw nothing" (no_context) or the
    unrealistic "the agent saw every row" (raw_data_full_dump).
    """
    with customers_csv.open(newline="") as f:
        rows = list(csv.DictReader(f))

    numeric_cols = ["tenure_months", "discount", "monthly_charges"]

    lines = [f"Dataset: customers.csv, {len(rows)} rows, 6 columns.", "", "Schema:"]
    lines.append("  - customer_id: string (unique id)")
    for col in numeric_cols:
        vals = [float(r[col]) for r in rows]
        lines.append(
            f"  - {col}: numeric, min={min(vals):.2f} max={max(vals):.2f} "
            f"mean={mean(vals):.2f} median={median(vals):.2f} stdev={pstdev(vals):.2f}"
        )
    contract_counts = Counter(r["contract_type"] for r in rows)
    lines.append(
        "  - contract_type: categorical, values: "
        + ", ".join(f"{k}={v}" for k, v in contract_counts.most_common())
    )
    churn_rate = sum(1 for r in rows if r["churn"] == "true") / len(rows)
    lines.append(f"  - churn: boolean, overall churn rate={churn_rate:.1%}")

    rng = random.Random(seed)
    sample = rng.sample(rows, min(sample_size, len(rows)))
    lines.append("")
    lines.append(f"Sample of {len(sample)} rows:")
    lines.append(",".join(rows[0].keys()))
    lines.extend(",".join(r.values()) for r in sample)

    return (
        "Here is a profile of the customers dataset (schema, summary "
        "statistics, and a small random sample -- not the full "
        f"{n_rows} rows):\n\n" + "\n".join(lines)
    )


def build_churn_raw_data_context(customers_csv: Path, *, n_rows: int) -> str:
    """The naive full-dump baseline (--include-raw-dump). Not the default."""
    text = customers_csv.read_text()
    return (
        "Here is the complete customers dataset:\n\n"
        "```csv\n" + text.strip() + "\n```\n\n"
        f"The dataset has {n_rows} rows: customer_id, tenure_months, "
        "contract_type, discount, monthly_charges, and churn (true/false)."
    )


