def make_prompt(question: str, context: str | None = None) -> str:
    parts = []
    if context:
        parts.append(context)
        parts.append("")
    parts.append(f"Question: {question}")
    parts.append("")
    parts.append("Answer concisely.")
    return "\n".join(parts)


def count_tokens(client, model: str, text: str) -> int:
    """Approximate input token count."""
    resp = client.messages.count_tokens(
        model=model,
        messages=[{"role": "user", "content": text}],
    )
    return resp.input_tokens


def _first_text(resp) -> str | None:
    """Return the first text block's content, or None if the response has no
    text block at all.

    A response's content blocks aren't always [TextBlock, ...] -- a model with
    extended thinking on by default (observed: claude-opus-5) returns a
    ThinkingBlock first, so resp.content[0].text raised AttributeError here
    before this existed. None also covers the response being cut off by
    max_tokens before any text was produced (all thinking, no room left).
    """
    for block in resp.content:
        if getattr(block, "type", None) == "text":
            return block.text
    return None


def ask(client, model: str, prompt: str) -> str:
    resp = client.messages.create(
        model=model,
        # Generous, not just enough for a "concise" answer: a model with
        # extended thinking on by default spends part of this budget on
        # thinking blocks before any answer text, so a tight max_tokens can
        # leave zero room left for the text this function actually needs.
        max_tokens=1500,
        messages=[{"role": "user", "content": prompt}],
    )
    text = _first_text(resp)
    if text is None:
        raise RuntimeError(
            f"{model} returned no text block (stop_reason={resp.stop_reason!r}); "
            "it likely spent the whole max_tokens budget on thinking -- raise "
            "the max_tokens in ask() if this model always thinks first"
        )
    return text


def judge(client, model: str, question: str, reference: str, response: str) -> int | None:
    prompt = textwrap.dedent(f"""\
        You are evaluating an AI response.

        Question: {question}
        Reference answer: {reference}
        Response to evaluate: {response}

        Rate the response from 1 to 5:
        1 = wrong or irrelevant
        2 = partially relevant but mostly wrong
        3 = roughly correct but vague or missing key details
        4 = correct with minor gaps
        5 = correct and specific

        Reply with only the number.""")

    resp = client.messages.create(
        model=model,
        # Same reasoning as ask() above: 8 was enough for a bare digit with no
        # thinking, but leaves no room for a model that thinks by default.
        max_tokens=400,
        messages=[{"role": "user", "content": prompt}],
    )
    text = _first_text(resp)
    if text is None:
        return None
    # Lenient on purpose: "Reply with only the number" isn't always followed
    # to the letter (e.g. "Rating: 5" or "5/5"), so take the first 1-5 digit
    # in the reply rather than requiring the whole string to be just that
    # digit.
    match = re.search(r"[1-5]", text)
    return int(match.group()) if match else None


