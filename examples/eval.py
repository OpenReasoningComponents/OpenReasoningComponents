def run_iris(args, client) -> list[dict]:
    components = load_iris_components(args.components)
    conditions = [
        ("no_context", None),
        ("profile", build_iris_profile_context(seed=args.seed)),
        ("components", build_iris_component_context(components)),
    ]
    if args.include_raw_dump:
        conditions.append(("raw_data_full_dump", build_iris_raw_data_context()))
    summary = _run_and_report(
        args, client, IRIS_QUESTIONS, conditions, label="iris (150 rows)"
    )
    return [summary] if summary else []


def run_churn(args, client) -> list[dict]:
    summaries = []
    for size in args.sizes:
        customers_csv = (Path(args.tmp_dir or ".") / f"customers_{size}.csv").resolve()
        generate_customers_csv(customers_csv, rows=size, seed=args.seed)

        component_context = build_churn_component_context(customers_csv)
        profile_context = build_churn_profile_context(
            customers_csv, n_rows=size, seed=args.seed
        )
        conditions = [
            ("no_context", None),
            ("profile", profile_context),
            ("components", component_context),
        ]
        if args.include_raw_dump:
            raw_context = build_churn_raw_data_context(customers_csv, n_rows=size)
            conditions.append(("raw_data_full_dump", raw_context))
        summary = _run_and_report(
            args, client, CHURN_QUESTIONS, conditions, label=f"churn ({size} rows)"
        )
        if summary:
            summaries.append(summary)
    return summaries


def _run_and_report(args, client, questions, conditions, *, label: str) -> dict | None:
    """Run one (questions, conditions) group and print a summary.

    Returns a structured summary (one entry per condition: avg_tokens,
    avg_score/n_scored if --judge was passed) for --results-json/--chart to
    consume, or None under --dry-run, where there's nothing real to chart.
    """
    print(f"\n{'#' * 70}\n# {label}\n{'#' * 70}")

    if args.dry_run:
        for name, context in conditions:
            sample_prompt = make_prompt(questions[0]["question"], context)
            print(f"\n--- {name}: {len(sample_prompt)} chars (no API call) ---")
            print(sample_prompt[:300] + ("..." if len(sample_prompt) > 300 else ""))
        return None

    scores = {name: [] for name, _ in conditions}
    tokens = {name: [] for name, _ in conditions}

    for q in questions:
        print(f"\n{'=' * 70}\nQ: {q['question']}\nReference: {q['reference']}\n{'=' * 70}")

        for name, context in conditions:
            prompt = make_prompt(q["question"], context)
            for _trial in range(args.trials):
                tok = count_tokens(client, args.model, prompt)
                tokens[name].append(tok)
                response = ask(client, args.model, prompt)

                print(f"\n--- {name} ({tok} tokens) ---")
                print(response)

                if args.judge:
                    judge_model = args.judge_model or args.model
                    score = judge(client, judge_model, q["question"], q["reference"], response)
                    if score is not None:
                        scores[name].append(score)
                        print(f"  [score: {score}/5]")

    print(f"\n{'=' * 70}\nSUMMARY: {label}\n{'=' * 70}")
    if args.judge and not args.judge_model:
        print(
            "  NOTE: judge model == answer model "
            f"({args.model}). Same-model judging is biased toward its own "
            "family's answers; pass --judge-model for an independent score."
        )
    condition_summaries = []
    for name, _ in conditions:
        t = tokens[name]
        avg_tok = mean(t) if t else 0
        s = scores.get(name, [])
        line = f"  {name:15s}  avg_tokens={avg_tok:.0f}"
        if s:
            line += f"  avg_score={mean(s):.1f}  n={len(s)}"
        print(line)
        condition_summaries.append(
            {
                "name": name,
                "avg_tokens": avg_tok,
                "avg_score": mean(s) if s else None,
                "n_scored": len(s),
            }
        )

    return {
        "label": label,
        "answer_model": args.model,
        "judge_model": (args.judge_model or args.model) if args.judge else None,
        "trials": args.trials,
        "conditions": condition_summaries,
    }


def render_chart(results: list[dict], path: Path) -> None:
    """Render a grouped bar chart (avg score, avg tokens) from run summaries.

    Needs matplotlib, imported here rather than at module level: a plain
    --dry-run or a run without --chart needs nothing beyond this script's usual
    dependencies. One group of bars per result label (e.g. one per --sizes
    value); one bar per condition (no_context/profile/components/...), colored
    consistently across groups so the same condition reads as the same color
    everywhere.
    """
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as exc:
        raise SystemExit(
            "rendering a chart needs matplotlib: pip install matplotlib"
        ) from exc

    if not results:
        raise SystemExit("no results to chart (did every run hit --dry-run?)")

    condition_names: list[str] = []
    for result in results:
        for condition in result["conditions"]:
            if condition["name"] not in condition_names:
                condition_names.append(condition["name"])

    has_scores = any(
        condition["avg_score"] is not None
        for result in results
        for condition in result["conditions"]
    )

    labels = [result["label"] for result in results]
    x_positions = list(range(len(labels)))
    width = 0.8 / len(condition_names)
    colors = plt.get_cmap("tab10").colors

    def _grouped_bars(ax, key: str, ylabel: str, *, log: bool = False) -> None:
        for i, name in enumerate(condition_names):
            values = []
            for result in results:
                match = next(
                    (c for c in result["conditions"] if c["name"] == name), None
                )
                values.append((match or {}).get(key) or 0)
            offsets = [
                xi + (i - (len(condition_names) - 1) / 2) * width for xi in x_positions
            ]
            ax.bar(offsets, values, width=width, label=name, color=colors[i % len(colors)])
        ax.set_xticks(x_positions)
        ax.set_xticklabels(labels, rotation=15, ha="right")
        ax.set_ylabel(ylabel)
        if log:
            ax.set_yscale("log")
            # Headroom so the legend (upper left) doesn't sit on top of the
            # tallest bar -- a log axis needs a multiplicative margin, not the
            # additive one matplotlib's default autoscale would give it.
            ax.set_ylim(top=ax.get_ylim()[1] * 3)
        ax.legend(fontsize=8)

    n_panels = 2 if has_scores else 1
    # A floor on width even for one panel: the subtitle (model/judge/trials) is
    # long enough to overflow a single 6" panel.
    fig, axes = plt.subplots(1, n_panels, figsize=(max(6 * n_panels, 9), 4.5))
    axes = [axes] if n_panels == 1 else list(axes)

    if has_scores:
        _grouped_bars(axes[0], "avg_score", "avg score (1-5, higher is better)")
        axes[0].set_ylim(0, 5.5)
        _grouped_bars(axes[1], "avg_tokens", "avg input tokens (log scale)", log=True)
    else:
        _grouped_bars(axes[0], "avg_tokens", "avg input tokens (log scale)", log=True)

    first = results[0]
    subtitle = f"model: {first['answer_model']}"
    if first["judge_model"]:
        subtitle += f"  |  judge: {first['judge_model']}"
        if first["judge_model"] == first["answer_model"]:
            subtitle += "  (same-model judge -- biased; see README)"
    else:
        subtitle += "  |  no --judge: token counts only, no accuracy score"
    subtitle += f"  |  trials: {first['trials']}"

    fig.suptitle("ORC components vs. baselines")
    fig.text(0.5, 0.93, subtitle, ha="center", fontsize=9, color="dimgray")
    fig.tight_layout(rect=(0, 0, 1, 0.90))
    fig.savefig(path, dpi=150)
    print(f"\nChart written to {path}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate ORC components vs raw data vs no context."
    )
    parser.add_argument(
        "--dataset", choices=["iris", "churn"], default="churn",
        help="iris: the original, 150-row, single-size demo. churn "
        "(default): a synthetic dataset generated at one or more sizes.",
    )
    parser.add_argument("--model", default="claude-sonnet-5")
    parser.add_argument(
        "--judge-model", default=None,
        help="Model to use for --judge scoring, if different from --model. "
        "Strongly recommended: a same-model judge is biased.",
    )
    parser.add_argument("--judge", action="store_true")
    parser.add_argument(
        "--trials", type=int, default=1,
        help="Repeat each question this many times per condition.",
    )
    parser.add_argument(
        "--sizes", type=int, nargs="+", default=[500, 5000],
        help="(--dataset churn only) dataset sizes to test, to see whether "
        "the token gap between raw_data and components widens with scale.",
    )
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--tmp-dir", default=None)
    parser.add_argument(
        "--components", default="examples/components.json",
        help="(--dataset iris only) path to components JSON file.",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Build every prompt and print its size without calling the "
        "Anthropic API at all (no API key needed). Use this to sanity-check "
        "contexts before spending a real run.",
    )
    parser.add_argument(
        "--include-raw-dump", action="store_true",
        help="Also run a 'raw_data_full_dump' condition: the entire CSV in "
        "the prompt. Off by default because no real system does this; it's "
        "here only as an explicit naive upper bound, not the headline "
        "comparison (see the module docstring).",
    )
    parser.add_argument(
        "--results-json", type=Path, default=None,
        help="Write structured results (one entry per label/condition: "
        "avg_tokens, avg_score, n_scored) to this path. Ignored under "
        "--dry-run, where there are no real scores to record.",
    )
    parser.add_argument(
        "--chart", type=Path, default=None,
        help="Render a grouped bar chart (avg score if --judge was passed, "
        "avg tokens always) to this path (e.g. eval_results.png). Needs "
        "matplotlib (pip install matplotlib). Ignored under --dry-run.",
    )
    args = parser.parse_args()

    client = None
    if not args.dry_run:
        from anthropic import Anthropic

        client = Anthropic()

    if args.dataset == "iris":
        results = run_iris(args, client)
    else:
        results = run_churn(args, client)

    if args.results_json and results:
        args.results_json.write_text(json.dumps(results, indent=2))
        print(f"\nResults written to {args.results_json}")
    if args.chart and results:
        render_chart(results, args.chart)


if __name__ == "__main__":
    main()
